// Regenerates src/languageDetector/zhScripts.ts from OpenCC's character tables (Apache-2.0):
// the characters used in only one of Simplified and Traditional Chinese.
// Run with `node scripts/gen-zh-scripts.mjs` after bumping OPENCC_COMMIT.
import { writeFileSync } from "node:fs";

const OPENCC_COMMIT = "fae2a0a911c30764e669a7d8b0591cd8e852934a";
const OUT = "src/languageDetector/zhScripts.ts";

/** [key, values] rows of an OpenCC dictionary file. */
async function table(name) {
  const url = `https://raw.githubusercontent.com/BYVoid/OpenCC/${OPENCC_COMMIT}/data/dictionary/${name}.txt`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url}: ${String(res.status)}`);
  return (await res.text())
    .split("\n")
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => {
      const [key, values] = line.split("\t");
      return [key, values.split(" ")];
    });
}

/** Keys that OpenCC always rewrites: they never stand in the other script. */
const rewritten = (rows) =>
  new Set(rows.filter(([key, values]) => !values.includes(key)).map(([key]) => key));

// Being listed is not enough: "呆 -> 呆 待" names 待 only as a variant, yet 待 is in both.
const simplified = rewritten(await table("STCharacters")); // Simplified -> Traditional
const traditional = rewritten(await table("TSCharacters")); // Traditional -> Simplified
// A few variants (緼, 醖, ...) are rewritten both ways; they decide nothing.
const only = (set, other) => [...set].filter((ch) => !other.has(ch)).join("");

writeFileSync(
  OUT,
  `// Generated by scripts/gen-zh-scripts.mjs from OpenCC ${OPENCC_COMMIT} (Apache-2.0).
// Characters OpenCC always rewrites for the other script; every other Han character can stand in both.
export const SIMPLIFIED_ONLY =
  "${only(simplified, traditional)}";
export const TRADITIONAL_ONLY =
  "${only(traditional, simplified)}";
`
);
console.log(`Wrote ${OUT}`);
